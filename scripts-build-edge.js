/* Regenerates the Supabase Edge Function that serves the dashboard.
   The page is gzipped and base64'd into the function so it is self-contained:
   nothing is fetched at request time, so there is no second thing to keep alive.

   Usage:
     node build.js                 # refresh dist/
     node scripts-build-edge.js    # write supabase/functions/okng/index.ts
     supabase functions deploy okng --no-verify-jwt --project-ref <ref>

   verify_jwt must stay off: a browser loading a page cannot send an
   Authorization header. Only the markup is public — every row it displays
   comes from Supabase behind RLS, which grants reads to signed-in users only. */
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const html = fs.readFileSync(path.join('dist', 'okng-monitor-v3.html'));
const b64 = zlib.gzipSync(html, { level: 9 }).toString('base64');

const src = `import "jsr:@supabase/functions-js/edge-runtime.d.ts";

// Generated by scripts-build-edge.js — do not edit by hand.
const GZ_B64 =
  "${b64}";

const bytes = Uint8Array.from(atob(GZ_B64), (c) => c.charCodeAt(0));
const html = await new Response(
  new Blob([bytes]).stream().pipeThrough(new DecompressionStream("gzip")),
).text();

Deno.serve((req: Request) => {
  if (req.method !== "GET" && req.method !== "HEAD") {
    return new Response("Method not allowed", { status: 405 });
  }
  return new Response(req.method === "HEAD" ? null : html, {
    headers: {
      "content-type": "text/html; charset=utf-8",
      "cache-control": "public, max-age=300",
      "x-content-type-options": "nosniff",
    },
  });
});
`;

const out = path.join('supabase', 'functions', 'okng', 'index.ts');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, src);
console.log(out, '—', (html.length / 1024).toFixed(1), 'KB page →',
  (src.length / 1024).toFixed(1), 'KB function');
